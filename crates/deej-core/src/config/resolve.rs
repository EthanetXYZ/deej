//! Viper-compatible value conversion.
//!
//! The original deej read its config with viper 1.7.1, which parsed YAML with Go's yaml.v2 (YAML 1.1 rules)
//! and converted values with spf13/cast 1.3.0. Users' files were written against that behaviour, so it is
//! reproduced here rather than using YAML 1.2 typing:
//!
//! - [`resolve`] mirrors yaml.v2's `resolve()` for plain (unquoted) scalars: `yes`/`on`/`y` are booleans,
//!   `010` is octal, `1_000` drops its underscores, `09` falls through to a float, and so on.
//! - [`to_string`], [`to_bool`] and [`to_int`] mirror cast's `ToString`, `ToBool` and `ToInt`.
//!
//! Every rule here is covered by the golden tests in `tests/golden_config.rs`, which compare against output
//! generated by the real Go libraries (`tools/golden-gen`).

use crate::yaml::{Node, NodeKind, Style};

/// A scalar after yaml.v2 type resolution.
#[derive(Debug, Clone, PartialEq)]
pub enum Scalar {
    Null,
    Bool(bool),
    Int(i64),
    Uint(u64),
    Float(f64),
    Str(String),
}

impl Scalar {
    /// True if this boolean came from one of YAML 1.1's word forms (`yes`, `off`, ...) rather than a
    /// number or string. Used to keep such words literal where deej Next deliberately differs (targets).
    pub fn is_bool(&self) -> bool {
        matches!(self, Scalar::Bool(_))
    }
}

/// Resolves a scalar node the way yaml.v2 does. Returns `None` for sequences and mappings.
pub fn resolve_node(node: &Node) -> Option<Scalar> {
    match &node.kind {
        NodeKind::Scalar { value, style, tag } => Some(resolve(value, *style, tag.as_deref())),
        _ => None,
    }
}

/// yaml.v2 `resolve()` for one scalar. Quoted scalars and `!!str` are always strings.
pub fn resolve(text: &str, style: Style, tag: Option<&str>) -> Scalar {
    if style == Style::Quoted || matches!(tag, Some("!!str" | "tag:yaml.org,2002:str" | "!!binary")) {
        return Scalar::Str(text.to_string());
    }

    match text {
        "" | "~" | "null" | "Null" | "NULL" => return Scalar::Null,
        "y" | "Y" | "yes" | "Yes" | "YES" | "true" | "True" | "TRUE" | "on" | "On" | "ON" => {
            return Scalar::Bool(true);
        }
        "n" | "N" | "no" | "No" | "NO" | "false" | "False" | "FALSE" | "off" | "Off" | "OFF" => {
            return Scalar::Bool(false);
        }
        ".inf" | ".Inf" | ".INF" | "+.inf" | "+.Inf" | "+.INF" => return Scalar::Float(f64::INFINITY),
        "-.inf" | "-.Inf" | "-.INF" => return Scalar::Float(f64::NEG_INFINITY),
        ".nan" | ".NaN" | ".NAN" => return Scalar::Float(f64::NAN),
        _ => {}
    }

    match text.as_bytes()[0] {
        // a '.' prefix can only be a float
        b'.' => match text.parse::<f64>() {
            Ok(f) if is_go_float_syntax(text) => Scalar::Float(f),
            _ => Scalar::Str(text.to_string()),
        },

        // digits and signs: int, then uint, then float (yaml.v2 strips underscores first).
        // timestamps are resolved by yaml.v2 too, but decoded back into strings for interface{} targets,
        // which is what viper uses - so they stay strings here
        b'0'..=b'9' | b'-' | b'+' => {
            let plain = text.replace('_', "");

            if let Some(i) = go_parse_int(&plain) {
                return match i64::try_from(i) {
                    Ok(v) => Scalar::Int(v),
                    Err(_) if (0..=u64::MAX as i128).contains(&i) && !plain.starts_with(['-', '+']) => {
                        Scalar::Uint(i as u64)
                    }
                    Err(_) => float_or_string(&plain, text),
                };
            }

            float_or_string(&plain, text)
        }

        _ => Scalar::Str(text.to_string()),
    }
}

fn float_or_string(plain: &str, original: &str) -> Scalar {
    if is_yaml_style_float(plain) {
        if let Ok(f) = plain.parse::<f64>() {
            return Scalar::Float(f);
        }
    }

    Scalar::Str(original.to_string())
}

/// yaml.v2's `yamlStyleFloat`: `^[-+]?(\.[0-9]+|[0-9]+(\.[0-9]*)?)([eE][-+]?[0-9]+)?$`
fn is_yaml_style_float(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;

    if i < b.len() && (b[i] == b'+' || b[i] == b'-') {
        i += 1;
    }

    let digits = |i: &mut usize| {
        let start = *i;
        while *i < b.len() && b[*i].is_ascii_digit() {
            *i += 1;
        }
        *i - start
    };

    if i < b.len() && b[i] == b'.' {
        i += 1;
        if digits(&mut i) == 0 {
            return false;
        }
    } else {
        if digits(&mut i) == 0 {
            return false;
        }
        if i < b.len() && b[i] == b'.' {
            i += 1;
            digits(&mut i);
        }
    }

    if i < b.len() && (b[i] == b'e' || b[i] == b'E') {
        i += 1;
        if i < b.len() && (b[i] == b'+' || b[i] == b'-') {
            i += 1;
        }
        if digits(&mut i) == 0 {
            return false;
        }
    }

    i == b.len()
}

/// Go's `strconv.ParseFloat` accepts a few forms Rust's parser doesn't and vice versa. For the '.'-prefixed
/// inputs this is used on, only plain decimal syntax matters.
fn is_go_float_syntax(s: &str) -> bool {
    is_yaml_style_float(s)
}

/// Go's `strconv.ParseInt(s, 0, 64)` (and `ParseUint`) syntax: optional sign, `0x`/`0o`/`0b` prefixes, a leading
/// `0` meaning octal, and underscores allowed between digits only when a base prefix rule permits them.
/// Returns the value as i128 so the caller can apply the int64/uint64 range checks.
pub fn go_parse_int(s: &str) -> Option<i128> {
    let (negative, body) = match s.as_bytes().first()? {
        b'-' => (true, &s[1..]),
        b'+' => (false, &s[1..]),
        _ => (false, s),
    };

    if body.is_empty() {
        return None;
    }

    let lower = body.to_ascii_lowercase();
    let (radix, digits, prefixed) = if let Some(rest) = lower.strip_prefix("0x") {
        (16, rest.to_string(), true)
    } else if let Some(rest) = lower.strip_prefix("0o") {
        (8, rest.to_string(), true)
    } else if let Some(rest) = lower.strip_prefix("0b") {
        (2, rest.to_string(), true)
    } else if lower.len() > 1 && lower.starts_with('0') {
        (8, lower[1..].to_string(), true)
    } else {
        (10, lower, false)
    };

    // from_str_radix would accept a second sign; Go doesn't
    if !digits.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return None;
    }

    if digits.contains('_') && !underscores_ok(&digits, prefixed) {
        return None;
    }

    let digits: String = digits.chars().filter(|&c| c != '_').collect();
    if digits.is_empty() {
        return None;
    }

    let magnitude = u64::from_str_radix(&digits, radix).ok()? as i128;
    let value = if negative { -magnitude } else { magnitude };

    (i128::from(i64::MIN)..=i128::from(u64::MAX)).contains(&value).then_some(value)
}

/// Go's `underscoreOK`: underscores only separate digits (or follow a base prefix), never lead, trail or repeat.
fn underscores_ok(digits: &str, prefixed: bool) -> bool {
    let mut previous_was_digit_or_prefix = prefixed;

    for c in digits.chars() {
        if c == '_' {
            if !previous_was_digit_or_prefix {
                return false;
            }
            previous_was_digit_or_prefix = false;
        } else {
            previous_was_digit_or_prefix = true;
        }
    }

    previous_was_digit_or_prefix
}

/// Go's `strconv.FormatFloat(f, 'f', -1, 64)`: shortest round-trip digits, never an exponent.
pub fn format_go_float(f: f64) -> String {
    if f.is_nan() {
        "NaN".to_string()
    } else if f == f64::INFINITY {
        "+Inf".to_string()
    } else if f == f64::NEG_INFINITY {
        "-Inf".to_string()
    } else {
        // Rust's Display for f64 is also shortest-round-trip without an exponent
        format!("{f}")
    }
}

/// cast 1.3.0 `ToString`. `None` means cast would fail (sequences and mappings), which viper turns into "".
pub fn to_string(node: &Node) -> Option<String> {
    resolve_node(node).map(|scalar| scalar_to_string(&scalar))
}

pub fn scalar_to_string(scalar: &Scalar) -> String {
    match scalar {
        Scalar::Null => String::new(),
        Scalar::Bool(b) => b.to_string(),
        Scalar::Int(i) => i.to_string(),
        Scalar::Uint(u) => u.to_string(),
        Scalar::Float(f) => format_go_float(*f),
        Scalar::Str(s) => s.clone(),
    }
}

/// cast 1.3.0 `ToBool`: booleans, non-zero ints, and strings accepted by Go's `strconv.ParseBool`.
/// Floats, unsigned ints too large for int64, and anything else are false.
pub fn to_bool(node: &Node) -> bool {
    match resolve_node(node) {
        Some(Scalar::Bool(b)) => b,
        Some(Scalar::Int(i)) => i != 0,
        Some(Scalar::Str(s)) => go_parse_bool(&s).unwrap_or(false),
        _ => false,
    }
}

/// Go's `strconv.ParseBool`.
pub fn go_parse_bool(s: &str) -> Option<bool> {
    match s {
        "1" | "t" | "T" | "TRUE" | "true" | "True" => Some(true),
        "0" | "f" | "F" | "FALSE" | "false" | "False" => Some(false),
        _ => None,
    }
}

/// cast 1.3.0 `ToInt`: ints as-is, floats truncated toward zero, bools as 1/0, strings through Go's
/// `strconv.ParseInt(s, 0, 0)` (so `"0x1C200"` and `"115_200"` work but `"115200.0"` doesn't). Anything else is 0.
pub fn to_int(node: &Node) -> i64 {
    match resolve_node(node) {
        Some(Scalar::Int(i)) => i,
        Some(Scalar::Uint(u)) => u as i64,
        Some(Scalar::Float(f)) if f.is_finite() => f.trunc() as i64,
        Some(Scalar::Bool(b)) => i64::from(b),
        Some(Scalar::Str(s)) => go_parse_int(&s).and_then(|v| i64::try_from(v).ok()).unwrap_or(0),
        _ => 0,
    }
}

/// True for an absent value as viper sees it: a plain null scalar (`key:`, `key: ~`).
pub fn is_null(node: &Node) -> bool {
    matches!(resolve_node(node), Some(Scalar::Null))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plain(s: &str) -> Scalar {
        resolve(s, Style::Plain, None)
    }

    #[test]
    fn yaml_1_1_words() {
        for t in ["y", "Yes", "ON", "true"] {
            assert_eq!(plain(t), Scalar::Bool(true), "{t}");
        }
        for f in ["n", "NO", "off", "False"] {
            assert_eq!(plain(f), Scalar::Bool(false), "{f}");
        }
        assert_eq!(plain("~"), Scalar::Null);
        assert_eq!(plain("nil"), Scalar::Str("nil".into()));
        assert_eq!(resolve("yes", Style::Quoted, None), Scalar::Str("yes".into()));
    }

    #[test]
    fn numbers_follow_go_parse_int_base_0() {
        assert_eq!(plain("010"), Scalar::Int(8));
        assert_eq!(plain("0x1F"), Scalar::Int(31));
        assert_eq!(plain("-0x10"), Scalar::Int(-16));
        assert_eq!(plain("0b101"), Scalar::Int(5));
        assert_eq!(plain("0o17"), Scalar::Int(15));
        assert_eq!(plain("1_0"), Scalar::Int(10));
        assert_eq!(plain("+5"), Scalar::Int(5));
        assert_eq!(plain("09"), Scalar::Float(9.0));
        assert_eq!(plain("1e3"), Scalar::Float(1000.0));
        assert_eq!(plain(".5"), Scalar::Float(0.5));
        assert_eq!(plain("18446744073709551615"), Scalar::Uint(u64::MAX));
        assert_eq!(plain("2020-01-02"), Scalar::Str("2020-01-02".into()));
        assert_eq!(plain("1.2.3"), Scalar::Str("1.2.3".into()));
    }

    #[test]
    fn go_float_formatting() {
        assert_eq!(format_go_float(1.5), "1.5");
        assert_eq!(format_go_float(9.0), "9");
        assert_eq!(format_go_float(1e21), "1000000000000000000000");
        assert_eq!(format_go_float(f64::INFINITY), "+Inf");
    }

    #[test]
    fn string_ints_allow_prefixes_and_underscores_but_not_decimals() {
        assert_eq!(go_parse_int("0x1C200"), Some(115_200));
        assert_eq!(go_parse_int("115_200"), Some(115_200));
        assert_eq!(go_parse_int("_1"), None);
        assert_eq!(go_parse_int("1__0"), None);
        assert_eq!(go_parse_int("115200.0"), None);
        assert_eq!(go_parse_int("08"), None);
    }
}
